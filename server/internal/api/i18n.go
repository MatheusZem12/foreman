// Portuguese messages for whoever uses the interface in Portuguese: the front end sends
// X-Lang: pt-BR. The key is the English text (or fmt format), as it is in the code; whatever
// isn't here goes out in English.

type langKey struct{}

// withLang keeps the request's language in the context.
func withLang(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasPrefix(strings.ToLower(r.Header.Get("X-Lang")), "pt") {
			r = r.WithContext(context.WithValue(r.Context(), langKey{}, "pt-BR"))
		}
		next.ServeHTTP(w, r)
	})
}

func portuguese(ctx context.Context) bool { return ctx.Value(langKey{}) == "pt-BR" }

// tr translates the format and the text arguments found in the map.
func tr(ctx context.Context, format string, args ...any) string {
	if portuguese(ctx) {
		if pt, ok := ptMsgs[format]; ok {
			format = pt
		}
		args = append([]any(nil), args...)
		for i, a := range args {
			if s, ok := a.(string); ok {
				if pt, ok := ptMsgs[s]; ok {
					args[i] = pt
				}
			}
		}
	}
	if len(args) == 0 {
		return format
	}
	return fmt.Sprintf(format, args...)
}

