package runner

import (
	"fmt"
	"strings"

	"foreman/internal/store"
)

func skillsIndex(skills []store.Skill, dirOf func(store.Skill) string) string {
	if len(skills) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("## Available skills\n")
	b.WriteString("These are ready-made guides and scripts kept by the team. When the task fits a skill's description, " +
		"read its SKILL.md before starting and follow what it says (the scripts it mentions sit in the same folder).\n\n")
	for _, s := range skills {
		desc := s.Description
		if desc == "" {
			desc = "no description"
		}
		fmt.Fprintf(&b, "- **%s** — %s\n  arquivo: %s/SKILL.md\n", s.Name, desc, dirOf(s))
	}
	return b.String()
}

func buildSystem(agent *store.Agent, skills []store.Skill, dirOf func(store.Skill) string) string {
	var parts []string
	if t := strings.TrimSpace(agent.Instructions); t != "" {
		parts = append(parts, t)
	}
	if idx := skillsIndex(skills, dirOf); idx != "" {
		parts = append(parts, idx)
	}
	return strings.Join(parts, "\n\n")
}

type promptRepo struct {
	Slug, Path, Name, Description, Base string
	Commits                             string
	Conflicts                           []string
}

type promptInput struct {
	Key         string
	Issue       *store.Issue
	Repos       []promptRepo
	Root        string
	Kind        string
	Request     string
	Requester   *store.User
	SummaryPath string
	StatusPath  string
	History     string // previous runs (generated by Foreman)
}

func buildPrompt(in promptInput) string {
	is := in.Issue
	var parts []string
	parts = append(parts, fmt.Sprintf("# %s-%d: %s", in.Key, is.Number, is.Title))
	if d := strings.TrimSpace(is.Description); d != "" {
		parts = append(parts, d)
	}
	rules := "- Don't switch branches and don't merge, rebase, commit or push: at the end Foreman commits what you leave and publishes the branch.\n" +
		"- The environment is isolated: you can only write in this folder (and in the package cache, already set up). Install dependencies and run tests normally."
	if len(in.Repos) == 1 {
		rp := in.Repos[0]
		parts = append(parts, "## Environment\n"+
			fmt.Sprintf("- You are in an isolated git worktree (`%s`) of the **%s** repository, on branch `%s`, created from `%s`.\n", rp.Path, rp.Name, is.Branch, rp.Base)+
			"- Work only here.\n"+rules)
	} else {
		var b strings.Builder
		fmt.Fprintf(&b, "## Environment\nThe `%s` folder has an isolated worktree of each repository in this workspace, all on branch `%s`:\n\n", in.Root, is.Branch)
		for _, rp := range in.Repos {
			desc := strings.TrimSpace(rp.Description)
			if desc == "" {
				desc = "no description"
			}
			fmt.Fprintf(&b, "- `%s/` — **%s**: %s (base `%s`)", rp.Slug, rp.Name, desc, rp.Base)
			b.WriteString("\n")
		}
		b.WriteString("\n- Work out from the request which repositories need to change and touch only those; don't explore the others. " +
			"A repository without changes gets no branch and no merge.\n" +
			"- Before changing a repository, read its instructions file, if there is one.\n" + rules)
		parts = append(parts, b.String())
	}
	if in.Requester != nil && strings.TrimSpace(in.Requester.About) != "" {
		parts = append(parts, fmt.Sprintf("## Who asked\n%s — %s", in.Requester.Name, strings.TrimSpace(in.Requester.About)))
	}
	if s := strings.TrimSpace(is.Summary); s != "" || in.History != "" {
		block := "## What has already been done on this issue\nYou start without the history of the previous conversations; the issue's README and the history below are the context.\n\n" + s
		if in.History != "" {
			block += "\n\n### Request history (recorded by Foreman)\n" + in.History
		}
		var commits []string
		for _, rp := range in.Repos {
			if rp.Commits != "" {
				commits = append(commits, fmt.Sprintf("%s/\n%s", rp.Slug, rp.Commits))
			}
		}
		if len(commits) > 0 {
			block += "\n\nBranch commits:\n```\n" + strings.Join(commits, "\n\n") + "\n```"
		}
		parts = append(parts, block)
	}
	switch in.Kind {
	case "followup":
		parts = append(parts, "## Adjustment request\n"+strings.TrimSpace(in.Request))
	case "conflict":
		var list []string
		for _, rp := range in.Repos {
			for _, f := range rp.Conflicts {
				if len(in.Repos) == 1 {
					list = append(list, "- "+f)
				} else {
					list = append(list, fmt.Sprintf("- %s/%s", rp.Slug, f))
				}
			}
		}
		parts = append(parts, "## Resolve conflicts\n"+
			fmt.Sprintf("Merging the target branch into this branch stopped with conflicts in:\n%s\n\n", strings.Join(list, "\n"))+
			"Resolve every conflict preserving the intent of both sides, remove the `<<<<<<<` `=======` `>>>>>>>` markers "+
			"and make sure the project still works. Don't run `git commit` or `git merge --abort`: Foreman concludes the merge.")
	default:
		if r := strings.TrimSpace(in.Request); r != "" {
			parts = append(parts, "## Note\n"+r)
		}
	}
	parts = append(parts, "## When you finish\n"+
		fmt.Sprintf("1. Update the issue's README `%s`, overwriting it with the complete, cumulative version (in the language the issue is written in, up to ~60 lines):\n", in.SummaryPath)+
		"   - **Goal** — 1 line\n"+
		"   - **What was done** — per request, oldest to newest\n"+
		"   - **Repositories and main files**\n"+
		"   - **Decisions and reasons**\n"+
		"   - **How to test** and **open items**\n"+
		"   It is the record people read and the only context the next run (a new chat) will have.\n"+
		fmt.Sprintf("2. Write a single line in `%s` saying how it ended:\n", in.StatusPath)+
		"   - `done` — the request was fully handled;\n"+
		"   - `waiting: <what you need from the person>` — a decision, access, data or someone's confirmation is missing;\n"+
		"   - `incomplete: <what was missing and why>` — it couldn't be finished.\n"+
		"   When in doubt between finishing on risky assumptions and asking, ask (`waiting`).\n"+
		"3. End with a short answer saying what changed.")
	return strings.Join(parts, "\n\n")
}

// Divide "--foo 'a b' --bar" respeitando aspas.
func splitArgs(s string) []string {
	var out []string
	var cur strings.Builder
	var quote rune
	inToken := false
	for _, r := range s {
		switch {
		case quote != 0:
			if r == quote {
				quote = 0
			} else {
				cur.WriteRune(r)
			}
		case r == '"' || r == '\'':
			quote, inToken = r, true
		case r == ' ' || r == '\t' || r == '\n':
			if inToken {
				out = append(out, cur.String())
				cur.Reset()
				inToken = false
			}
		default:
			cur.WriteRune(r)
			inToken = true
		}
	}
	if inToken {
		out = append(out, cur.String())
	}
	return out
}
